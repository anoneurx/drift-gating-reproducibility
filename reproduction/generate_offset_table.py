#!/usr/bin/env python3
"""Generate the LaTeX source for Table IX (boundary-offset detection) directly
from raw detection CSVs. No number is typed by hand.

Includes the five original offsets and two additional offsets not tied to the
controller epoch size W=2000 (333 and 1501 references). Detection is counted
within a 30,000-reference absolute window after each recorded boundary, as in
the simulator.
"""
import csv
import os

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "latex", "offset_table.tex")
OFFSETS = [0, 250, 333, 500, 1000, 1370, 1501]
SCENARIOS = ["abrupt", "gradual", "recurring", "composite"]
LABELS = {"abrupt": "Abrupt", "gradual": "Gradual",
          "recurring": "Recurring", "composite": "Composite"}


def path_for(o):
    return os.path.join(HERE, "main_study_detection.csv" if o == 0 else f"detection_offset{o}.csv")


def totals(path, scen):
    rows = [r for r in csv.DictReader(open(path)) if r["scenario"] == scen]
    b = sum(int(r["n_bounds"]) for r in rows)
    d = sum(int(r["detected"]) for r in rows)
    s = sum(int(r["spurious"]) for r in rows)
    return b, d, s


def main():
    lines = []
    lines.append(r"\begin{table}[!t]")
    lines.append(r"\caption{Detection with shifted phase boundaries. Each cell is \emph{detected / spurious} confirmations within a 30,000-reference absolute window after a recorded boundary; true boundaries per scenario: 100, 100, 100, 80 (zero for stable). Offsets 333 and 1501 are not multiples of the controller epoch size ($W{=}2000$). Generated by \texttt{generate\_offset\_table.py} from raw detection CSVs.}")
    lines.append(r"\label{tab:offset}")
    lines.append(r"\scriptsize")
    lines.append(r"\setlength{\tabcolsep}{2.5pt}")
    cols = "@{}l" + "r" * len(OFFSETS) + "@{}"
    lines.append(r"\begin{tabular}{" + cols + "}")
    lines.append(r"\toprule")
    lines.append("Scenario & " + " & ".join(f"{o:,}" for o in OFFSETS) + r" \\")
    lines.append(r"\multicolumn{8}{@{}l@{}}{\emph{Phase offset (references)}} \\")
    lines.append(r"\midrule")
    for scen in SCENARIOS:
        cells = []
        for o in OFFSETS:
            b, d, s = totals(path_for(o), scen)
            cells.append(f"{d}/{s}")
        lines.append(f"{LABELS[scen]} & " + " & ".join(cells) + r" \\")
    lines.append(r"\midrule")
    for label, scen_list in [("All non-stable", SCENARIOS), ("Stable", ["stable"])]:
        cells = []
        for o in OFFSETS:
            ts = [totals(path_for(o), sc) for sc in scen_list]
            d = sum(t[1] for t in ts)
            s = sum(t[2] for t in ts)
            cells.append(f"{d}/{s}")
        lines.append(f"{label} & " + " & ".join(cells) + r" \\")
    lines.append(r"\bottomrule")
    lines.append(r"\end{tabular}")
    lines.append(r"\end{table}")
    text = "\n".join(lines) + "\n"
    with open(OUT, "w") as f:
        f.write(text)
    print(text)
    print(f"Wrote {OUT}")


if __name__ == "__main__":
    main()
