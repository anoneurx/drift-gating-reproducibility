#!/usr/bin/env python3
"""Re-run the controller-selection sweep with the released simulator.

This replaces the earlier, non-reproducible sweep that used `sim_study.cpp`.
The grid and the selection rule are exactly those described in Section V-B:

    candidate-set size {4, 5, 6}
    cost margin K     {0, 0.05, 0.1, 0.2}
    evaluation delay  {2, 5, 10, 20}

Training uses seed 100 with 15 stable and 32 non-stable traces
(`--stable-per-prim 3 --per-scenario 8`).  Test traces (seed 5001) are not
generated by this script and are never touched.

Selection rule: among configurations with zero false confirmations on stable
training traces after reference 100,000, choose the lowest mean non-stable
training miss ratio.  Ties are broken by smaller candidate set, then smaller K,
then smaller evaluation delay.

Usage:
    python3 sweep_selection.py [--jobs 4]
"""
import argparse
import concurrent.futures as cf
import csv
import os
import subprocess
import sys
from collections import defaultdict

HERE = os.path.dirname(os.path.abspath(__file__))
SIM = os.path.join(HERE, "sim_full")
RAW = os.path.join(HERE, "sweep_raw")
NONSTABLE = ("abrupt", "gradual", "recurring", "composite")
NCAND = (4, 5, 6)
KFRAC = (0.0, 0.05, 0.1, 0.2)
EDELAY = (2, 5, 10, 20)
SEED = 100
Z = 1.28


def mean(xs):
    return sum(xs) / len(xs) if xs else float("nan")


def run_one(cfg):
    ncand, kfrac, edelay = cfg
    tag = f"nc{ncand}_k{kfrac:g}_e{edelay}"
    out = os.path.join(RAW, tag + ".csv")
    det = os.path.join(RAW, tag + "_det.csv")
    cmd = [
        SIM,
        "--seed", str(SEED),
        "--stable-per-prim", "3",
        "--per-scenario", "8",
        "--da-only",
        "--ncand", str(ncand),
        "--kfrac", str(kfrac),
        "--z", str(Z),
        "--edelay", str(edelay),
        "--out", out,
        "--det", det,
    ]
    subprocess.run(cmd, check=True, stdout=subprocess.DEVNULL,
                   stderr=subprocess.DEVNULL)
    rows = list(csv.DictReader(open(out)))
    da = [r for r in rows if r["method"] == "DA"]
    ns = [float(r["miss_ratio"]) for r in da if r["scenario"] in NONSTABLE]
    st = [float(r["miss_ratio"]) for r in da if r["scenario"] == "stable"]
    drows = list(csv.DictReader(open(det)))
    stable_false = sum(int(r["false_after_100k"]) for r in drows
                       if r["scenario"] == "stable")
    spur = sum(int(r["spurious"]) for r in drows
               if r["scenario"] in NONSTABLE)
    nb = sum(int(r["n_bounds"]) for r in drows
             if r["scenario"] in NONSTABLE)
    detn = sum(int(r["detected"]) for r in drows
               if r["scenario"] in NONSTABLE)
    return {
        "ncand": ncand,
        "kfrac": kfrac,
        "edelay": edelay,
        "train_miss_nonstable": mean(ns),
        "train_miss_stable": mean(st),
        "stable_false_after_100k": stable_false,
        "spurious": spur,
        "detected": detn,
        "boundaries": nb,
        "detection_rate": (100.0 * detn / nb) if nb else 0.0,
    }


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--jobs", type=int, default=4,
                    help="parallel simulator processes (default 4)")
    args = ap.parse_args()

    if not os.path.exists(SIM):
        print("sim_full not found; building it first", file=sys.stderr)
        subprocess.run(["g++", "-O2", "-std=c++17", "-o", SIM,
                        os.path.join(HERE, "sim_full.cpp")], check=True)
    os.makedirs(RAW, exist_ok=True)

    cfgs = [(n, k, e) for n in NCAND for k in KFRAC for e in EDELAY]
    print(f"Running {len(cfgs)} configurations with {args.jobs} workers ...",
          file=sys.stderr)
    results = []
    with cf.ProcessPoolExecutor(max_workers=args.jobs) as ex:
        for r in ex.map(run_one, cfgs):
            print(f"  ncand={r['ncand']} K={r['kfrac']:g} delay={r['edelay']}: "
                  f"train={r['train_miss_nonstable']:.4f} "
                  f"stable_false={r['stable_false_after_100k']} "
                  f"spurious={r['spurious']}", file=sys.stderr)
            results.append(r)

    out = os.path.join(HERE, "sweep_results.csv")
    fields = ["ncand", "kfrac", "edelay", "train_miss_nonstable",
              "train_miss_stable", "stable_false_after_100k", "spurious",
              "detected", "boundaries", "detection_rate"]
    with open(out, "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=fields)
        w.writeheader()
        for r in results:
            w.writerow({k: (f"{r[k]:.5f}" if isinstance(r[k], float) else r[k])
                        for k in fields})

    eligible = [r for r in results if r["stable_false_after_100k"] == 0]
    if not eligible:
        print("No configuration had zero stable false confirmations.",
              file=sys.stderr)
        sys.exit(1)
    best = min(eligible, key=lambda r: (r["train_miss_nonstable"], r["ncand"],
                                        r["kfrac"], r["edelay"]))
    print("\nSelected configuration (lowest training miss, zero stable false):")
    print(f"  ncand={best['ncand']}  K={best['kfrac']:g}  edelay={best['edelay']}")
    print(f"  training non-stable miss={best['train_miss_nonstable']:.4f}")
    with open(os.path.join(HERE, "sweep_selected.txt"), "w") as f:
        f.write(f"ncand={best['ncand']}\n")
        f.write(f"kfrac={best['kfrac']:g}\n")
        f.write(f"edelay={best['edelay']}\n")
        f.write(f"z={Z}\n")
        f.write(f"train_miss_nonstable={best['train_miss_nonstable']:.5f}\n")
        f.write(f"stable_false_after_100k={best['stable_false_after_100k']}\n")
    print(f"\nWrote {out} and sweep_selected.txt")


if __name__ == "__main__":
    main()
